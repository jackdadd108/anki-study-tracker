const assert=require('node:assert/strict');
const Micro=require('../static/micro.js');
const now=Date.parse('2026-10-19T16:00:00Z');
const event=(id,offset=1000)=>({id,answered_at:new Date(now+offset).toISOString()});
const prior=event('prior',-1000),state=Micro.create(5,10,[prior],now);
assert.throws(()=>Micro.create(7,10,[],now),/increments of 5/);
assert.throws(()=>Micro.create(5,0,[],now),/time/);
assert.equal(Micro.stats(state,[prior,event('a'),event('a'),event('b')],now+2000).completed,2);
assert.equal(Micro.stats(state,[event('a')],now+2000).left,598000);
const complete=Array.from({length:5},(_,i)=>event(String(i),1000+i));
assert.equal(Micro.stats(state,complete,now+2000).reached,true);
assert.equal(Micro.stats(state,complete,now+700000).reached,true);
assert.equal(Micro.stats(state,[event('late',600001)],now+700000).completed,0);
assert.equal(Micro.stats(state,[],now+600000).expired,true);
assert.equal(Micro.stats(state,[],now+600000).left,0);
assert.equal(Micro.stats(state,[event('future',3000)],now+2000).completed,0);
assert.deepEqual(Micro.stats(JSON.parse(JSON.stringify(state)),complete,now+2000),Micro.stats(state,complete,now+2000));
const restart=Micro.create(5,5,complete,now+3000);
assert.equal(Micro.stats(restart,[...complete,event('next',4000)],now+5000).completed,1);
assert.equal(Micro.stats(null,[],now),null);
console.log('Micro target checks passed: increments, timer, deduplication, deadline, restoration and restart.');
